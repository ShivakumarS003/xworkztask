package com.xworkz.methodOverriding.plastic.Plastic;

public class Plastic {
    public void melt() {
        System.out.println("Plastic: Melting at high temperature");
    }

    public void mold() {
        System.out.println("Plastic: Can be molded into shapes");
    }

    public void insulate() {
        System.out.println("Plastic: Acts as an insulator");
    }

    public void floatInWater() {
        System.out.println("Plastic: Floats due to low density");
    }

    public void nonBiodegradable() {
        System.out.println("Plastic: Takes years to decompose");
    }
}
