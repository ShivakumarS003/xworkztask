package com.xworkz.methodOverriding.theaters.theater;

public class Theater {
    public void openShow() {
        System.out.println("Theater: Opening the show");
    }

    public void dimLights() {
        System.out.println("Theater: Dimming the lights");
    }

    public void playScene() {
        System.out.println("Theater: Performing a scene");
    }

    public void takeBreak() {
        System.out.println("Theater: Taking intermission");
    }

    public void closeShow() {
        System.out.println("Theater: Closing the curtains");
    }
}
