package com.xworkz.methodOverriding.Water.water;

public class Water {
    public void flow() {
        System.out.println("Water: Flowing through rivers and pipes");
    }

    public void evaporate() {
        System.out.println("Water: Evaporating due to heat");
    }

    public void freeze() {
        System.out.println("Water: Freezing into ice at low temperatures");
    }

    public void boil() {
        System.out.println("Water: Boiling at 100 degrees Celsius");
    }

    public void sustainLife() {
        System.out.println("Water: Essential for all living organisms");
    }
}
