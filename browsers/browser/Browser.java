package com.xworkz.methodOverriding.browsers.browser;

public class Browser {
    public void open() {
        System.out.println("Browser: Opening browser");
    }

    public void loadPage() {
        System.out.println("Browser: Loading page");
    }

    public void refresh() {
        System.out.println("Browser: Refreshing page");
    }

    public void bookmark() {
        System.out.println("Browser: Bookmarking page");
    }

    public void close() {
        System.out.println("Browser: Closing browser");
    }
}

