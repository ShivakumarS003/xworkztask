package com.xworkz.methodOverriding.shoes.shoe;

public class Shoe {
    public void wear() {
        System.out.println("Shoe: Wearing the shoe");
    }

    public void polish() {
        System.out.println("Shoe: Polishing for shine");
    }

    public void remove() {
        System.out.println("Shoe: Removing the shoe");
    }

    public void tieLaces() {
        System.out.println("Shoe: Tying the laces");
    }

    public void clean() {
        System.out.println("Shoe: Cleaning the shoe surface");
    }
}
