package com.xworkz.methodOverriding.birds.bird;

public class Bird {
    public void fly() {
        System.out.println("Bird: Flying");
    }

    public void sing() {
        System.out.println("Bird: Singing");
    }

    public void buildNest() {
        System.out.println("Bird: Building nest");
    }

    public void layEggs() {
        System.out.println("Bird: Laying eggs");
    }

    public void eat() {
        System.out.println("Bird: Eating grains");
    }
}
