package com.xworkz.methodOverriding.actors.actor;

public class Actor {
    public void act() {
        System.out.println("Actor: Performing in a scene");
    }

    public void rehearse() {
        System.out.println("Actor: Rehearsing script");
    }

    public void promote() {
        System.out.println("Actor: Promoting movie");
    }

    public void attendEvent() {
        System.out.println("Actor: Attending award show");
    }

    public void rest() {
        System.out.println("Actor: Taking a break");
    }
}

