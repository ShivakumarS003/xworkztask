package com.xworkz.methodOverriding.banks.bank;

public class Bank {
    public void openAccount() {
        System.out.println("Bank: Account opened");
    }

    public void provideLoan() {
        System.out.println("Bank: Loan provided");
    }

    public void issueCard() {
        System.out.println("Bank: Card issued");
    }

    public void netBanking() {
        System.out.println("Bank: Net banking available");
    }

    public void closeAccount() {
        System.out.println("Bank: Account closed");
    }
}

