package com.xworkz.methodOverriding.tools.tool;

public class Tool {
    public void use() {
        System.out.println("Tool: Being used for a task");
    }

    public void repair() {
        System.out.println("Tool: Undergoing maintenance or repair");
    }

    public void store() {
        System.out.println("Tool: Being stored safely after use");
    }

    public void clean() {
        System.out.println("Tool: Getting cleaned after work");
    }

    public void inspect() {
        System.out.println("Tool: Being inspected for wear and tear");
    }
}
