package com.xworkz.methodOverriding.Libraries.library;

public class Library {
    public void issueBook() {
        System.out.println("Library: Book issued");
    }

    public void returnBook() {
        System.out.println("Library: Book returned");
    }

    public void addBook() {
        System.out.println("Library: Book added to shelf");
    }

    public void removeBook() {
        System.out.println("Library: Book removed");
    }

    public void searchBook() {
        System.out.println("Library: Searching book");
    }
}
