package com.xworkz.methodOverriding.Hospitals.hospital;

public class Hospital {
    public void admit() {
        System.out.println("Hospital: Admitting patient");
    }

    public void diagnose() {
        System.out.println("Hospital: Diagnosing illness");
    }

    public void treat() {
        System.out.println("Hospital: Providing treatment");
    }

    public void discharge() {
        System.out.println("Hospital: Discharging patient");
    }

    public void maintainRecords() {
        System.out.println("Hospital: Maintaining medical records");
    }
}
