package com.xworkz.methodOverriding.retruants.retruant;

public class Restaurant {
    public void open() {
        System.out.println("Restaurant: Opening for the day");
    }

    public void serveFood() {
        System.out.println("Restaurant: Serving meals to customers");
    }

    public void cleanTables() {
        System.out.println("Restaurant: Cleaning tables regularly");
    }

    public void prepareBill() {
        System.out.println("Restaurant: Preparing the bill");
    }

    public void close() {
        System.out.println("Restaurant: Closing operations");
    }
}
