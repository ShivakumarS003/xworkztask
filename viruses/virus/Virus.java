package com.xworkz.methodOverriding.viruses.virus;

public class Virus {
    public void infect() {
        System.out.println("Virus: Infecting host cells");
    }

    public void replicate() {
        System.out.println("Virus: Replicating inside host");
    }

    public void mutate() {
        System.out.println("Virus: Mutating to survive");
    }

    public void spread() {
        System.out.println("Virus: Spreading to new hosts");
    }

    public void triggerImmuneResponse() {
        System.out.println("Virus: Triggering immune response in host");
    }
}
