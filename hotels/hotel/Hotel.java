package com.xworkz.methodOverriding.hotels.hotel;

public class Hotel {
    public void bookRoom() {
        System.out.println("Hotel: Room booked");
    }

    public void serveFood() {
        System.out.println("Hotel: Serving food");
    }

    public void cleanRoom() {
        System.out.println("Hotel: Cleaning room");
    }

    public void checkout() {
        System.out.println("Hotel: Guest checked out");
    }

    public void manageStaff() {
        System.out.println("Hotel: Managing hotel staff");
    }
}
