package com.xworkz.methodOverriding.soil.Soil;

public class Soil {
    public void absorbWater() {
        System.out.println("Soil: Absorbing water into the ground");
    }

    public void supportPlants() {
        System.out.println("Soil: Providing support to plant roots");
    }

    public void retainNutrients() {
        System.out.println("Soil: Retaining essential nutrients");
    }

    public void filterWater() {
        System.out.println("Soil: Filtering water as it passes through");
    }

    public void hostMicroorganisms() {
        System.out.println("Soil: Hosting beneficial microorganisms");
    }
}
