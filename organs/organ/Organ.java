package com.xworkz.methodOverriding.organs.organ;

public class Organ {
    public void function() {
        System.out.println("Organ: Performing body function");
    }

    public void supplyBlood() {
        System.out.println("Organ: Supplying blood");
    }

    public void connectNerves() {
        System.out.println("Organ: Connecting with nervous system");
    }

    public void grow() {
        System.out.println("Organ: Growing over time");
    }

    public void regenerate() {
        System.out.println("Organ: Attempting to regenerate");
    }
}
